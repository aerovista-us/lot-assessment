import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { verifyProjectImportSources } from "../lib/project-import-source-verifier.mjs";
const pondy = JSON.parse(readFileSync(new URL("../projects/import-manifests/pondy-lot2.json", import.meta.url)));
const fakeSuccess = async () => ({ ok: true, json: async () => ({ type: "file", sha: "a".repeat(40) }) });
const verified = await verifyProjectImportSources(pondy, { fetchImpl: fakeSuccess });
assert.equal(verified.ok, true);
assert.equal(verified.plan.allSourcesVerified, true);
assert.equal(verified.plan.importState, "NOT_PERSISTED");
assert.equal(verified.plan.reportRelease, "WITHHELD");
assert.equal(verified.plan.automaticPublication, false);
assert.equal(verified.plan.mutationAllowed, false);
const missing = await verifyProjectImportSources(pondy, { fetchImpl: async () => ({ ok: false, status: 404 }) });
assert.equal(missing.ok, false);
assert.equal(missing.plan.artifacts[0].sourceStatus, "NOT_FOUND");
const invalid = await verifyProjectImportSources({ ...pondy, sourceRepository: "other/repo" }, { fetchImpl: () => { throw Error("should not fetch invalid"); } });
assert.equal(invalid.code, "INVALID_MANIFEST");
const unavailable = await verifyProjectImportSources(pondy, { fetchImpl: () => { throw Error("network down"); } });
assert.equal(unavailable.ok, false);
assert.ok(unavailable.plan.artifacts.every(a => a.sourceStatus === "UNAVAILABLE"));
const nonFile = await verifyProjectImportSources(pondy, { fetchImpl: async () => ({ ok: true, json: async () => ({ type: "dir", sha: "b".repeat(40) }) }) });
assert.equal(nonFile.ok, false);
assert.equal(nonFile.plan.artifacts[0].sourceStatus, "NOT_A_FILE");
console.log("PASS: source validation, missing, invalid, outage, non-file, no persistence/publication");
