import assert from 'node:assert/strict';
import {pondyCandidateRegistry as registry} from '../projects/pondy-lot2/candidate-registry.ts';
import {buildReportRoofGallery} from '../packages/candidates/customer-report-roof-gallery.ts';
import {createCandidateConceptHtml} from '../packages/candidates/customer-report.ts';

const original=registry.candidates.find(c=>c.id==='pondy-d4');
assert(original,'Current locked Design 4 roof reference missing');
const gallery=buildReportRoofGallery(original);
assert.equal(gallery.status,'MODEL_GEOMETRY_LOCKED');
assert.equal(gallery.views.length,20,'All four owners × five cameras must appear');
assert.equal(new Set(gallery.views.map(v=>v.ownerId)).size,4);
assert.equal(gallery.valleys,2,'Both Home B source valley cuts required');
assert.equal((gallery.html.match(/data-roof-owner="/g)||[]).length,4);
assert.equal((gallery.html.match(/data-roof-camera="/g)||[]).length,20);
assert.equal((gallery.html.match(/data-roof-valley="/g)||[]).length,2);
assert.equal((gallery.html.match(/data-section-status="SOURCE_INTERSECTION"/g)||[]).length,2);
assert.match(gallery.html,/data-interval-status="VISIBLE"/);
assert.match(gallery.html,/data-interval-status="HIDDEN"/);
assert.match(gallery.html,/data-interval-status="UNRESOLVED"/);
assert.match(gallery.html,/data-gallery-authority="REVIEW_REQUIRED"/);
assert.match(gallery.html,/NOT an architect-certified roof/);
assert.match(gallery.html,/Drainage, flashing and structural review outstanding/);
for(const direction of ['NORTH','SOUTH','EAST','WEST']){
 const v=gallery.views.find(x=>x.ownerId==='home-b'&&x.camera===direction);
 assert.equal(v?.status,'REVIEW_REQUIRED','Home B '+direction+' must retain unresolved source projections');
 assert(v.counts.unresolved>0,'Home B '+direction+' cannot pass without zero unresolved');
}
assert.equal(gallery.views.find(x=>x.ownerId==='home-b'&&x.camera==='AXON')?.status,'INTERVAL_VERIFIED');
const report=await createCandidateConceptHtml(original);
assert.equal((report.html.match(/data-report-feature="/g)||[]).length,22);
assert.equal((report.html.match(/data-roof-camera="/g)||[]).length,20);
assert(report.html.includes('id="roof-evidence"'));
assert(report.html.includes('Roof source projection and junction evidence'));
assert(report.html.includes('No drainage, structural, fascia, architectural hidden-line or AHJ approval'));
assert(report.html.includes('CONCEPT ONLY — NOT FOR CONSTRUCTION'));
assert(report.html.includes('data-source-sha256="'+report.sha+'"'));
const stale=registry.candidates.find(c=>c.id==='pondy-d4b-rot35b');
assert(stale);
const blocked=buildReportRoofGallery(stale);
assert.equal(blocked.status,'REVIEW_REQUIRED');
assert.equal(blocked.views.length,0);
assert.equal(blocked.valleys,0);
assert(!blocked.html.includes('<svg'));
assert((await createCandidateConceptHtml(stale)).html.includes('Roof geometry exists but one or more owners are unlocked'));
const missing=structuredClone(original);
missing.id='test-roof-absent';
missing.revisionLabel='Test roof absent';
missing.components=missing.components.filter(c=>c.kind!=='roof');
const withheld=buildReportRoofGallery(missing);
assert.equal(withheld.status,'WITHHELD');
assert.equal(withheld.views.length,0);
assert(!withheld.html.includes('data-roof-edge='));
assert(!(await createCandidateConceptHtml(missing)).html.includes('data-roof-owner='));
const changed=structuredClone(original);
const owner=changed.components.find(c=>c.id==='home-b');
assert(owner&&owner.kind==='home');
owner.x+=3;
if(owner.polygon)owner.polygon=owner.polygon.map(p=>[p[0]+3,p[1]]);
const moved=buildReportRoofGallery(changed);
assert.equal(moved.status,'REVIEW_REQUIRED','Moved owner must invalidate all roof projections');
assert(!moved.html.includes('<svg'));
console.log('PASS: locked 20 camera intervals + 2 source Home B valley cuts; unresolved cardinal projections retained; stale/moved/absent source refuses all roof drawings');
